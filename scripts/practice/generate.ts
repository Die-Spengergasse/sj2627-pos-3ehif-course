/**
 * Turns exercises into Gradle projects, as an in-memory file tree:
 *
 *   materialsTree(...)  the multi-project build students clone (one subproject per chapter)
 *   zipTree(...)        a standalone project with a single exercise (the "Download as zip" fallback)
 *
 * The output is deterministic: same exercises and template, same files and bytes.
 */
import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { zipSync, type Zippable } from 'fflate';
import { CHAPTER_SLUGS, CHAPTERS, MODULES, type ChapterSlug } from '../../src/lib/content/modules.ts';
import { typeLineIndex, type Exercise } from './exercises.ts';

export type FileEntry = { data: Uint8Array; executable?: boolean };
/** Path (posix, relative to the project root) -> file. */
export type Tree = Map<string, FileEntry>;

const MTIME = new Date(2000, 0, 1, 0, 0, 0);
const IGNORED = new Set(['.DS_Store', 'Thumbs.db']);
const EXECUTABLE = new Set(['gradlew']);
/** Template files stored without the leading dot, so they do not affect the site repository. */
const DOTFILES: Record<string, string> = { gitignore: '.gitignore', gitattributes: '.gitattributes' };

const text = (s: string): FileEntry => ({ data: new TextEncoder().encode(s) });

/** Gradle subproject folder of a chapter (the chapter slug). */
export const chapterProject = (chapter: ChapterSlug) => chapter;

function listFiles(dir: string): string[] {
	const out: string[] = [];
	const walk = (current: string) => {
		for (const name of readdirSync(current)) {
			if (IGNORED.has(name)) continue;
			const full = join(current, name);
			if (statSync(full).isDirectory()) walk(full);
			else out.push(relative(dir, full).split(sep).join('/'));
		}
	};
	walk(dir);
	return out.sort();
}

/** Wrapper, version catalog, gradle.properties and dotfiles from practice/_template (without chapters/). */
function templateFiles(templateDir: string): Tree {
	const tree: Tree = new Map();
	for (const path of listFiles(templateDir)) {
		if (path.startsWith('chapters/')) continue;
		const target = DOTFILES[path] ?? path;
		tree.set(target, { data: new Uint8Array(readFileSync(join(templateDir, path))), executable: EXECUTABLE.has(path) });
	}
	return tree;
}

/** Extra build script lines of a chapter (practice/_template/chapters/<chapter>.gradle.kts), or "". */
function chapterExtras(templateDir: string, chapter: ChapterSlug): string {
	const file = join(templateDir, 'chapters', `${chapter}.gradle.kts`);
	return existsSync(file) ? readFileSync(file, 'utf8').trim() : '';
}

export function settingsGradle(name: string, chapters: ChapterSlug[]): string {
	return `// Generated by the POS 3EHIF learning site. Do not edit: changes are overwritten.
plugins {
    // Downloads the JDK from gradle/libs.versions.toml if it is not installed.
    id("org.gradle.toolchains.foojay-resolver-convention") version "1.0.0"
}

rootProject.name = "${name}"

dependencyResolutionManagement {
    repositories {
        mavenCentral()
    }
}

${chapters.map((c) => `include("${chapterProject(c)}")`).join('\n')}
`;
}

export function chapterBuildGradle(chapter: ChapterSlug, extras: string): string {
	const title = CHAPTERS.find((c) => c.slug === chapter)!.title;
	return `// Generated by the POS 3EHIF learning site. Do not edit: changes are overwritten.
// Exercises of the chapter "${title}".
plugins {
    java
}

group = "at.spengergasse.pos3"

java {
    toolchain {
        languageVersion = JavaLanguageVersion.of(libs.versions.java.get().toInt())
    }
}

dependencies {
    testImplementation(platform(libs.junit.jupiter.bom))
    testImplementation("org.junit.jupiter:junit-jupiter")
    testImplementation(libs.assertj.core)
    testRuntimeOnly("org.junit.platform:junit-platform-launcher")
}
${extras ? `\n${extras}\n` : ''}
tasks.withType<JavaCompile> {
    options.encoding = "UTF-8"
}

tasks.test {
    useJUnitPlatform()
}
`;
}

/** The task as a Markdown doc comment (`///`, Java 23+) in front of the exercise class. */
export function withTask(source: string, className: string, title: string, task: string): string {
	const lines = source.split('\n');
	const at = typeLineIndex(source, className);
	if (at < 0) throw new Error(`no top-level type ${className}`);
	// Annotations directly above the type belong to it; the comment goes above them.
	let start = at;
	while (start > 0 && lines[start - 1].trim().startsWith('@')) start--;
	const doc = [`# ${title}`, '', ...task.split('\n')].map((l) => (l ? `/// ${l}` : '///'));
	return [...lines.slice(0, start), ...doc, ...lines.slice(start)].join('\n');
}

/** Source files of one exercise inside its chapter project. `useSolution` swaps in solution/ files. */
export function exerciseFiles(e: Exercise, useSolution = false): Tree {
	const tree: Tree = new Map();
	const base = (set: 'main' | 'test') => `${chapterProject(e.chapter)}/src/${set}/java/${e.pkg.replace(/\./g, '/')}`;
	for (const [name, source] of Object.entries(e.main)) {
		const content = useSolution && e.solution[name] ? e.solution[name] : source;
		const final = name === `${e.className}.java` ? withTask(content, e.className, e.title, e.task) : content;
		tree.set(`${base('main')}/${name}`, text(final));
	}
	for (const [name, source] of Object.entries(e.test)) tree.set(`${base('test')}/${name}`, text(source));
	return tree;
}

function readme(exercises: Exercise[], standalone: boolean): string {
	const intro = standalone
		? `This project contains one exercise of the POS 3EHIF learning site.

Open this folder in IntelliJ (**File → Open**) and wait until Gradle has finished importing.`
		: `All exercises of the POS 3EHIF learning site. One Gradle subproject per chapter.

## Setup (once)

1. In IntelliJ: **File → New → Project from Version Control**, paste the URL of this repository, **Clone**.
2. Wait until Gradle has finished importing. If JDK ${'{java}'} is missing, Gradle downloads it.

## New exercises

**Git → Update Project** (Ctrl+T / ⌘T). Your own changes stay; new exercises are added.
Published exercises never change, so updating does not conflict with your work.`;
	const rows = exercises.map((e) => {
		const chapter = CHAPTERS.find((c) => c.slug === e.chapter)!;
		const module = MODULES.find((m) => m.slug === e.module)!;
		return `| ${chapter.note} · ${module.title} | ${e.title}${e.kind === 'bonus' ? ' (bonus)' : ''} | \`${e.className}\` |`;
	});
	return `# POS 3EHIF · Exercises

${intro}

## Working on an exercise

1. On the learning site, click **Copy class name** on the exercise.
2. In IntelliJ press **Shift Shift**, paste, **Enter**. The task is at the top of the class.
3. Run the tests: green ▶ next to the class \`<ClassName>Test\`. When all tests are green, you are done.

There are no sample solutions. Ask in class if you get stuck.

## Exercises

| Module | Exercise | Class |
|---|---|---|
${rows.join('\n')}
`;
}

function withJavaVersion(tree: Tree, readmeText: string): FileEntry {
	const catalog = new TextDecoder().decode(tree.get('gradle/libs.versions.toml')?.data);
	const java = /^java\s*=\s*"(\d+)"/m.exec(catalog)?.[1] ?? '';
	return text(readmeText.replace('{java}', java));
}

const byCourseOrder = (a: Exercise, b: Exercise) =>
	MODULES.findIndex((m) => m.slug === a.module) - MODULES.findIndex((m) => m.slug === b.module) ||
	a.slug.localeCompare(b.slug);

function project(templateDir: string, name: string, exercises: Exercise[], standalone: boolean, useSolution: boolean): Tree {
	const sorted = [...exercises].sort(byCourseOrder);
	const chapters = CHAPTER_SLUGS.filter((c) => sorted.some((e) => e.chapter === c));
	const tree = templateFiles(templateDir);
	tree.set('settings.gradle.kts', text(settingsGradle(name, chapters)));
	for (const c of chapters) {
		tree.set(`${chapterProject(c)}/build.gradle.kts`, text(chapterBuildGradle(c, chapterExtras(templateDir, c))));
	}
	for (const e of sorted) for (const [path, entry] of exerciseFiles(e, useSolution)) tree.set(path, entry);
	tree.set('README.md', withJavaVersion(tree, readme(sorted, standalone)));
	return new Map([...tree].sort(([a], [b]) => a.localeCompare(b)));
}

/** The materials repository: every published exercise. */
export function materialsTree(templateDir: string, exercises: Exercise[], options: { useSolution?: boolean } = {}): Tree {
	return project(templateDir, 'pos3-exercises', exercises.filter((e) => e.published), false, options.useSolution ?? false);
}

/** A standalone project with one exercise. */
export function zipTree(templateDir: string, exercise: Exercise): Tree {
	return project(templateDir, `pos3-${exercise.slug}`, [exercise], true, false);
}

/** Zips a tree. Same input gives the same bytes; gradlew stays executable. */
export function zipBytes(tree: Tree): Uint8Array {
	const entries: Zippable = {};
	for (const [path, { data, executable }] of tree) {
		entries[path] = [data, { mtime: MTIME, level: 6, os: 3, attrs: (executable ? 0o100755 : 0o100644) << 16 }];
	}
	return zipSync(entries);
}

/** Writes a tree into `dir`, replacing everything in it except `.git`. */
export function writeTree(tree: Tree, dir: string): void {
	mkdirSync(dir, { recursive: true });
	for (const name of readdirSync(dir)) if (name !== '.git') rmSync(join(dir, name), { recursive: true, force: true });
	for (const [path, { data, executable }] of tree) {
		const file = join(dir, path);
		mkdirSync(dirname(file), { recursive: true });
		writeFileSync(file, data);
		if (executable) chmodSync(file, 0o755);
	}
}
